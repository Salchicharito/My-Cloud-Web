-- Consultas para mostrar que los cambios hechos con la API quedaron en ESCUELA
USE ESCUELA;

SELECT * FROM ALUMNO;
SELECT * FROM MATERIA;
SELECT * FROM PROFESOR;

SELECT AM.ID, A.NOMBRE AS ALUMNO, M.NOMBRE AS MATERIA, AM.CALIFICACION
FROM ALUMNO_MATERIA AM
JOIN ALUMNO A ON A.ID = AM.ALUMNO_ID
JOIN MATERIA M ON M.ID = AM.MATERIA_ID;

SELECT PM.ID, P.NOMBRE AS PROFESOR, M.NOMBRE AS MATERIA
FROM PROFESOR_MATERIA PM
JOIN PROFESOR P ON P.ID = PM.PROFESOR_ID
JOIN MATERIA M ON M.ID = PM.MATERIA_ID;
